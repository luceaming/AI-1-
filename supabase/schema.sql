-- 사용 방법: Supabase 대시보드 > SQL Editor에 전체 내용을 붙여넣고 Run을 실행하세요.
-- ============================================================================

-- 1. 비식별 스미싱·정상 문자 판별 사례 저장 테이블
create table if not exists public.smishing_cases (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  -- 입력 방식: 'text'(텍스트 직접 입력), 'image'(캡처 이미지에서 AI 텍스트 변환), 'mixed'(혼합)
  input_type text not null default 'text' check (input_type in ('text', 'image', 'mixed')),

  -- 동일 비식별 문구 중복 저장 방지 및 Supabase 캐시 조회용 SHA-256 해시
  source_hash text not null unique,

  -- 개인정보(전화번호·계좌번호·주민번호·이메일) 마스킹이 완료된 텍스트
  masked_text text not null,

  -- 유사 사례 검색(RAG)을 위한 핵심 키워드 배열
  keywords text[] not null default '{}',

  -- OpenRouter(Gemma 4) 판별 결과 메타데이터
  risk_score integer not null check (risk_score >= 0 and risk_score <= 100),
  risk_level text not null check (risk_level in ('안전', '주의', '위험')),
  scam_type text not null,
  summary text not null,
  easy_summary text not null default '',
  signals jsonb not null default '[]'::jsonb,
  advice jsonb not null default '[]'::jsonb,
  model text not null default '',

  -- 동일 문구 재요청(캐시 히트) 횟수
  hit_count integer not null default 1
);

-- 2. 조회 및 RAG 검색 성능 향상을 위한 인덱스
create index if not exists idx_smishing_cases_created_at
  on public.smishing_cases (created_at desc);

create index if not exists idx_smishing_cases_scam_type
  on public.smishing_cases (scam_type);

create index if not exists idx_smishing_cases_keywords
  on public.smishing_cases using gin (keywords);

-- 3. updated_at 자동 갱신 트리거
create or replace function public.set_smishing_cases_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_smishing_cases_updated_at on public.smishing_cases;
create trigger trg_smishing_cases_updated_at
  before update on public.smishing_cases
  for each row
  execute function public.set_smishing_cases_updated_at();

-- 4. Row Level Security(RLS) 활성화
-- 브라우저에서 직접 DB에 접근하지 못하도록 차단하며,
-- Vercel 서버리스 함수(api/*.js)에서 SUPABASE_SERVICE_ROLE_KEY로만 안전하게 접근합니다.
alter table public.smishing_cases enable row level security;

-- 5. PostgREST API 스키마 캐시 즉시 갱신 및 테이블 생성 확인 결과 출력
-- (CREATE/ALTER 문만 실행하면 Supabase SQL Editor에 "Success. No rows returned"가 뜨므로
--  아래 SELECT로 실제 테이블 생성 여부를 표 형태로 바로 확인할 수 있게 합니다.)
notify pgrst, 'reload schema';

select
  table_schema,
  table_name,
  (select count(*) from public.smishing_cases) as current_row_count
from information_schema.tables
where table_schema = 'public'
  and table_name = 'smishing_cases';
